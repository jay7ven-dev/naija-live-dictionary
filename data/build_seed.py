def dedupe_by_id(entries: list[dict]) -> list[dict]:
    seen: set[str] = set()
    out: list[dict] = []
    for e in entries:
        if e["id"] in seen:
            raise ValueError(f"duplicate id: {e['id']}")
        seen.add(e["id"])
        out.append(e)
    return out


